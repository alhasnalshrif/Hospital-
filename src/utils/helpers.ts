import { ApiResponse } from '../types';

export const createResponse = <T>(
  success: boolean,
  data?: T,
  message?: string,
  error?: string
): ApiResponse<T> => {
  return {
    success,
    data,
    message,
    error,
  };
};

export const createSuccessResponse = <T>(data: T, message?: string): ApiResponse<T> => {
  return createResponse(true, data, message);
};

export const createErrorResponse = (error: string, statusCode?: number): ApiResponse => {
  return createResponse(false, undefined, undefined, error);
};

export const generateId = (): string => {
  return Math.random().toString(36).substr(2, 9);
};

export const generatePatientNumber = (): string => {
  const date = new Date();
  const year = date.getFullYear().toString().slice(-2);
  const month = (date.getMonth() + 1).toString().padStart(2, '0');
  const random = Math.floor(Math.random() * 10000).toString().padStart(4, '0');
  return `P${year}${month}${random}`;
};

